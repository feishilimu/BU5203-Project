"""
report.py - turns a run record into a readable Markdown report.

No AI here: the report is assembled by code from reviewed findings, so it can
never contain a sentence that didn't pass through the checks and the human.

Layout
  1. Status box (DRAFT / APPROVED, by whom)
  2. Summary and coverage per country
  3. Comparison table (one row per question, one column per country)
  4. A. Regulatory developments  /  B. Industry developments, per country
  5. Appendix: rejected findings, sources and access log, method
"""
from collections import defaultdict

CATEGORY_LABELS = {
    "scope": "What is covered",
    "who_bears_loss": "Who bears the loss",
    "bank_duty": "Duties on banks",
    "other_party_duty": "Duties on telcos / platforms",
    "customer_duty": "Customer duties",
    "claims_process": "Claims process and timelines",
    "limits": "Limits and caps",
    "upcoming_change": "Upcoming changes",
    "statistic": "Statistics",
    "other": "Other",
}
COMPARISON_ROWS = ["scope", "who_bears_loss", "limits", "claims_process", "upcoming_change"]


def _included(f: dict) -> bool:
    """Rejected findings never appear in the main body."""
    return not (f.get("review") and f["review"]["decision"] == "rejected")


def _cite(f: dict) -> str:
    page = f" p.{f['page']}" if f.get("page") else ""
    tier = "" if f["source_tier"] == 1 else " *(secondary source)*"
    link = f"[{f['source_title']}]({f['source_url']})" if f.get("source_url") else f["source_title"]
    return f"{link}{page}{tier}"


def _badges(f: dict) -> str:
    parts = []
    if f.get("review"):
        r = f["review"]
        parts.append(f"**Reviewer: {r['decision']}**" + (f" – {r['note']}" if r.get("note") else ""))
    else:
        parts.append("*Not yet reviewed*")
    parts += [f"⚠️ {fl['code']} ({fl['severity']})" for fl in f["flags"]]
    return " · ".join(parts)


def to_markdown(record: dict) -> str:
    findings = record["findings"]
    included = [f for f in findings if _included(f)]
    approved = record["status"] == "approved"
    out = [f"# Scam & Fraud Liability – External Driver Report",
           ""]
    if approved:
        a = record["approval"]
        out.append(f"> ✅ **APPROVED** by {a['reviewer']} on {a['at']}")
    else:
        out.append("> ⚠️ **DRAFT – NOT FOR RELIANCE.** Generated by an AI-assisted tool; "
                   "awaiting human review and approval.")
    out += ["",
            f"Run `{record['run_id']}` · created {record['created_at']} · "
            f"AI: {record['llm']['provider']} ({record['llm']['model']}), {record['llm'].get('calls', 0)} calls",
            "",
            "## Summary",
            f"- Findings: {len(findings)} total, {len(included)} included, "
            f"{len(findings) - len(included)} rejected by reviewer",
            f"- Flagged findings: {sum(1 for f in findings if f['flags'])}",
            f"- Reviewed: {sum(1 for f in findings if f.get('review'))} of {len(findings)}",
            "",
            "### Coverage by jurisdiction",
            "| Jurisdiction | Sources read | Findings | Not read |",
            "|---|---|---|---|"]
    for j, c in record.get("coverage", {}).items():
        out.append(f"| {j} | {c['sources_read']}/{c['sources_selected']} | {c['findings']} | "
                   f"{'; '.join(c['sources_blocked_or_failed']) or '–'} |")

    # ---- comparison table: first included finding per (row, country) ----------
    js = record["jurisdictions"]
    out += ["", "## Comparison across jurisdictions",
            "*Each cell shows one cited finding; see the sections below for detail.*", "",
            "| Question | " + " | ".join(js) + " |", "|---" * (len(js) + 1) + "|"]
    for cat in COMPARISON_ROWS:
        cells = []
        for j in js:
            match = next((f for f in included if f["jurisdiction"] == j and f["category"] == cat), None)
            cells.append(f"{match['statement'][:180].replace('|', '/')} [{match['id']}]" if match else "Not found")
        out.append(f"| {CATEGORY_LABELS[cat]} | " + " | ".join(cells) + " |")

    # ---- sections A and B per country ----------------------------------------
    for section, heading in (("A", "A. Regulatory developments"), ("B", "B. Industry developments")):
        out += ["", f"## {heading}"]
        for j in js:
            fs = [f for f in included if f["jurisdiction"] == j and f["section"] == section]
            out += ["", f"### {j}"]
            if not fs:
                out.append("_No findings from the sources searched._")
                continue
            by_cat = defaultdict(list)
            for f in fs:
                by_cat[f["category"]].append(f)
            for cat, items in by_cat.items():
                out += ["", f"**{CATEGORY_LABELS.get(cat, cat)}**", ""]
                for f in items:
                    when = f" (status: {f['status']}" + (f", effective {f['effective_date']}" if f.get("effective_date") else "") + ")"
                    out += [f"- **[{f['id']}]** {f['statement']}{when}",
                            f"  - Source: {_cite(f)}",
                            f"  - Quote: “{f['quote']}”",
                            f"  - {_badges(f)}"]

    # ---- appendix ---------------------------------------------------------------
    rejected = [f for f in findings if not _included(f)]
    out += ["", "## Appendix A – Findings rejected by the reviewer"]
    out += [f"- [{f['id']}] {f['statement']} — reason: {f['review'].get('note') or 'none given'}"
            for f in rejected] or ["_None._"]
    out += ["", "## Appendix B – Sources and access log",
            "| Source | Status | Tier | Retrieved |", "|---|---|---|---|"]
    for a in record["access_log"]:
        name = f"[{a['title']}]({a['url']})" if a.get("url") else a["title"]
        out.append(f"| {name} | {a['status']}{' – ' + a['reason'] if a.get('reason') else ''} | "
                   f"{a.get('tier', '')} | {a.get('retrieved_at') or ''} |")
    out += ["", "## Appendix C – Method",
            "Documents were read in full, split into passages and ranked for relevance. An AI model "
            "extracted findings that must quote and cite a specific passage. Code-based checks then "
            "verified each quote and number against the source and flagged secondary sources, "
            "low-confidence findings and possible prompt injection. A human reviewer decided on "
            "flagged findings before approval. Sources were accessed in line with robots.txt, at a "
            "limited rate, with an identifying User-Agent, and cached as evidence."]
    return "\n".join(out)
